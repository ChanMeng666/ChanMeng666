#!/usr/bin/env node
// Generate wiki/: a local, Obsidian-browsable view of the profile shards, one page per entity.
//
//   wiki/index.md              the hubs, with counts, and pointers back to docs/INDEX.md and CLAUDE.md
//   wiki/<list>.md             a hub per list (projects grouped by tier then status, and so on)
//   wiki/<list>/<id>.md        one page per entry: frontmatter, summary, Links, Backlinks, Source
//   wiki/guards.md             every entry with a guard comment or a visibility flag set to hide it
//
// WHAT IT IS: a derived view, gitignored (`/wiki/`), deleted and rebuilt on every run, byte-for-byte
// the same for the same shards (no timestamps, file order everywhere). Nothing here is a source:
// edit the shard, then rebuild. Open `wiki/` as an Obsidian vault, or read it as plain markdown.
//
// WHAT IT READS: only the tracked shards in data/profile/ (through scripts/lib/load-profile.mjs)
// and the list of tracked story files in docs/stories/. Never a `*.private.*` file or `_private/`.
//
// LINKS: ids are unique per list, not across lists, so every link is `[[<list>/<id>]]`, never a
// bare slug. The field-to-list table below follows the shards and `.claude/rules/data-profile.md`;
// every field names one list (typed references, since 2026-10-16), and a value missing from that
// list is listed under "Unresolved references" in wiki/index.md. A field absent from an entry is
// skipped.
//
// Usage: node scripts/build-wiki.mjs [--quiet]

