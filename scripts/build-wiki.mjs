const { data, provenance } = loadProfileWithProvenance();

// Every array list whose entries carry an `id` gets pages. A list without ids (awards,
// certificates, productFilms today) still contributes backlinks, as plain text.
const entityLists = Object.keys(data).filter(
  (k) => Array.isArray(data[k]) && data[k].length > 0 && data[k].some((e) => e && typeof e === "object" && e.id)
);
const idSets = Object.fromEntries(entityLists.map((l) => [l, new Set(data[l].filter((e) => e?.id).map((e) => e.id))]));

// shard text, for line numbers and guard comments
const shardText = new Map();
function shardLines(file) {
  if (!shardText.has(file)) shardText.set(file, readUtf8(path.join(repoRoot, file)).split(/\r?\n/));
  return shardText.get(file);
}

function shardOf(list, index) {
  for (const seg of provenance[list] ?? []) {
    if (seg.start === undefined || (index >= seg.start && index < seg.end)) return seg.file;
  }
  return provenance[list]?.[0]?.file ?? null;
}

// Find the line of `id: <slug>` for an entry, inside the block of the list's top-level key, at the
// list-item indentation (so nested `id:` fields and same slugs in other lists do not match).
const lineCache = new Map();
function locate(list, file, id) {
  const key = `${file}::${list}`;
  if (!lineCache.has(key)) {
    const lines = shardLines(file);
    const top = lines.findIndex((l) => l === `${list}:` || l.startsWith(`${list}: `) || l.startsWith(`${list}:#`));
    let end = lines.length;
    for (let i = top + 1; i < lines.length; i++) {
      if (/^[A-Za-z_][\w-]*:/.test(lines[i])) {
        end = i;
        break;
      }
    }
    let itemIndent = null;
    for (let i = top + 1; i < end && itemIndent === null; i++) {
      const m = /^(\s*)- /.exec(lines[i]);
      if (m) itemIndent = m[1].length;
    }
    const map = new Map();
    if (top >= 0 && itemIndent !== null) {
      let itemStart = null;
      for (let i = top + 1; i < end; i++) {
        const l = lines[i];
        const dash = new RegExp(`^ {${itemIndent}}- `).test(l);
        if (dash) itemStart = i;
        const m =
          new RegExp(`^ {${itemIndent}}(?:- | {2})id:\\s*["']?([^"'#\\s]+)["']?\\s*(?:#.*)?$`).exec(l) ??
          new RegExp(`^ {${itemIndent}}- \\{\\s*id:\\s*["']?([^"',}\\s]+)`).exec(l); // flow-style row
        if (m && itemStart !== null && !map.has(m[1])) map.set(m[1], { idLine: i, itemStart });
      }
    }
    lineCache.set(key, { map, itemIndent, end });
  }
  return lineCache.get(key).map.get(id) ?? null;
}

// The contiguous comment block directly above an item's first line.
function commentAbove(file, itemStart) {
  const lines = shardLines(file);
  const out = [];
  for (let i = itemStart - 1; i >= 0; i--) {
    const t = lines[i].trim();
    if (!t.startsWith("#")) break;
    out.unshift({ line: i + 1, text: t.replace(/^#+\s?/, "") });
  }
  // Drop separator rules and section headings like "# ---- Games ----" at the top of the block.
  while (out.length && /^[-=#*\s]*$/.test(out[0].text)) out.shift();
  return out;
}

// Guard-style comments inside the entry's own lines (e.g. "repoUrl omitted … do not re-add").
function commentsInside(file, itemStart, nextStart) {
  const lines = shardLines(file);
  // The comment block (and blank lines) just before the next item belong to that item.
  let stop = nextStart;
  while (stop - 1 > itemStart && (lines[stop - 1].trim() === "" || lines[stop - 1].trim().startsWith("#"))) stop--;
  const blocks = [];
  let cur = null;
  for (let i = itemStart + 1; i < stop; i++) {
    const t = lines[i].trim();
    if (t.startsWith("#")) {
      if (!cur) cur = { line: i + 1, text: [] };
      cur.text.push(t.replace(/^#+\s?/, ""));
    } else if (cur) {
      blocks.push(cur);
      cur = null;
    }
  }
  if (cur) blocks.push(cur);
  return blocks.map((b) => ({ line: b.line, text: b.text.join(" ").trim() })).filter((b) => GUARD_RE.test(b.text));
}

// stories present (tracked files only; _private is never listed)
const storyDir = path.join(repoRoot, "docs", "stories");
const stories = new Set(
  fs.existsSync(storyDir)
    ? fs
        .readdirSync(storyDir)
        .filter((f) => f.endsWith(".md") && f !== "README.md")
        .map((f) => f.slice(0, -3))
    : []
);

// README / llms buckets in meta.x_brand: *ProjectIds arrays -> projects
const buckets = new Map(); // projectId -> [bucket]
const xb = data.meta?.x_brand ?? {};
for (const [k, v] of Object.entries(xb)) {
  if (!/ProjectIds$|OpenSourceIds$/.test(k) || !Array.isArray(v)) continue;
  for (const id of v) {
    if (typeof id !== "string") continue;
    if (!buckets.has(id)) buckets.set(id, []);
    buckets.get(id).push(k);
  }
}

// ---------------------------------------------------------------------------------------------
// resolve references (forward + backlinks)
// ---------------------------------------------------------------------------------------------
const forward = new Map(); // "list/id" -> [{ field, target: "list/id" | null, raw, note }]
const back = new Map(); // "list/id" -> [{ from: "list/id" | text, field }]
const unresolved = [];

// Every reference field is typed: it names exactly one list. A miss is reported, never guessed.
function resolveTarget(to, raw) {
  if (idSets[to]?.has(raw)) return { target: `${to}/${raw}` };
  return { target: null, note: `no ${to} entry` };
}

const allLists = Object.keys(REFS).filter((l) => Array.isArray(data[l]));
for (const list of allLists) {
  data[list].forEach((e, idx) => {
    if (!e || typeof e !== "object") return;
    const self = e.id ? `${list}/${e.id}` : null;
    const selfText = self ?? `${list}: ${oneLine(e.title ?? e.name ?? `#${idx + 1}`, 80)}`;
    for (const r of REFS[list]) {
      const vals = getPath(e, r.field);
      for (const v of vals) {
        const raw = r.pick ? r.pick(v) : v;
        if (typeof raw !== "string") continue;
        const to = r.targetFrom ? r.targetFrom(v) : r.to;
        const fieldName = r.label ?? r.field;
        const { target, note } = resolveTarget(to, raw);
        if (self) {
          if (!forward.has(self)) forward.set(self, []);
          forward.get(self).push({ field: fieldName, target, raw, note });
        }
        if (target) {
          if (!back.has(target)) back.set(target, []);
          back.get(target).push({ from: selfText, isLink: !!self, field: fieldName });
        } else {
          unresolved.push(`${selfText} ${fieldName} -> ${raw} (${note})`);
        }
      }
    }
  });
}

// ---------------------------------------------------------------------------------------------
// build pages
// ---------------------------------------------------------------------------------------------
const pages = new Map(); // relative path -> content
const guardRows = []; // { list, id, name, shard, line, kind, text }
const meta = new Map(); // "list/id" -> { name, e, shard, line }

for (const list of entityLists) {
  data[list].forEach((e, idx) => {
    if (!e?.id) return;
    const shard = shardOf(list, idx);
    const loc = shard ? locate(list, shard, e.id) : null;
    meta.set(`${list}/${e.id}`, { name: displayName(list, e), e, shard, line: loc ? loc.idLine + 1 : null, loc, idx });
  });
}

// item boundaries, for comments inside an entry
function nextItemStart(list, key) {
  const m = meta.get(key);
  if (!m?.loc) return m?.loc?.itemStart ?? 0;
  const later = [...meta.entries()]
    .filter(([k, v]) => k.startsWith(`${list}/`) && v.shard === m.shard && v.loc && v.loc.itemStart > m.loc.itemStart)
    .map(([, v]) => v.loc.itemStart);
  if (later.length) return Math.min(...later);
  return lineCache.get(`${m.shard}::${list}`)?.end ?? shardLines(m.shard).length;
}

function frontmatter(list, e, m) {
  const fm = { id: e.id, type: list };
  const nameKey = e.title && !e.name ? "title" : "name";
  fm[nameKey] = m.name;
  for (const k of DATE_KEYS) if (e[k] != null) fm[k] = String(e[k]);
  for (const k of ["status", "tier", "recency", "provenance", "kind", "type", "category"]) {
    if (e[k] != null && typeof e[k] !== "object") fm[k === "type" ? "entryType" : k] = e[k];
  }
  if (e.show != null) fm.show = e.show;
  if (e.sources != null) fm.sources = e.sources;
  fm.shard = m.shard;
  if (m.line) fm.line = m.line;
  if (stories.has(e.id)) fm.story = `docs/stories/${e.id}.md`;
  fm.aliases = [m.name];
  return `---\n${yaml.dump(fm, { lineWidth: -1, noRefs: true, sortKeys: false }).trimEnd()}\n---\n`;
}

for (const [key, m] of meta) {
  const [list] = key.split("/");
  const e = m.e;
  const out = [frontmatter(list, e, m), HEADER, "", `# ${m.name}`, ""];
  const sum = summaryOf(e);
  if (sum) out.push(sum, "");

  // guards on this entry
  const guards = [];
  if (m.loc) {
    const above = commentAbove(m.shard, m.loc.itemStart);
    const text = above.map((c) => c.text).join(" ").trim();
    if (text) guards.push({ kind: GUARD_RE.test(text) ? "guard comment" : "comment", line: above[0].line, text });
    for (const c of commentsInside(m.shard, m.loc.itemStart, nextItemStart(list, key))) {
      guards.push({ kind: "guard comment (field)", line: c.line, text: c.text });
    }
  }
  const flags = [];
  if (e.show && typeof e.show === "object") {
    for (const [s, v] of Object.entries(e.show)) if (v === false) flags.push(`show.${s}: false`);
  } else if (e.show === false) flags.push("show: false");
  for (const f of HIDE_FLAGS) if (f.test(e)) flags.push(typeof f.label === "function" ? f.label(e) : f.label);

  if (flags.length || guards.some((g) => g.kind !== "comment")) {
    out.push("## Visibility", "");
    for (const f of flags) out.push(`- ${f}`);
    for (const g of guards.filter((g) => g.kind !== "comment")) out.push(`- ${g.kind}, line ${g.line}: ${oneLine(g.text, 600)}`);
    out.push("", "Read the guard in the shard before touching a display list, a CV or LinkedIn copy.", "");
    for (const f of flags) guardRows.push({ key, list, name: m.name, shard: m.shard, line: m.line, kind: "flag", text: f });
    for (const g of guards.filter((g) => g.kind !== "comment"))
      guardRows.push({ key, list, name: m.name, shard: m.shard, line: g.line, kind: g.kind, text: g.text });
  }

  if (list === "projects" && buckets.has(e.id)) {
    out.push("## Display buckets", "", `\`meta.x_brand\` in data/profile/90-meta.yaml: ${buckets.get(e.id).join(", ")}`, "");
  }

  const fw = forward.get(key) ?? [];
  out.push("## Links", "");
  if (fw.length === 0) out.push("None.");
  for (const r of fw) {
    if (r.target) out.push(`- ${r.field}: [[${r.target}]]${r.note ? ` (${r.note})` : ""}`);
    else out.push(`- ${r.field}: ${r.raw} (unresolved: ${r.note})`);
  }
  out.push("");

  const bl = back.get(key) ?? [];
  out.push("## Backlinks", "");
  if (bl.length === 0) out.push("None.");
  for (const b of bl) out.push(`- ${b.isLink ? `[[${b.from}]]` : b.from} (${b.field})`);
  out.push("");

  out.push("## Source", "");
  out.push(`- Shard: \`${m.shard}${m.line ? `:${m.line}` : ""}\``);
  if (stories.has(e.id)) out.push(`- Story: [docs/stories/${e.id}.md](../../docs/stories/${e.id}.md)`);
  out.push("");
  pages.set(`${key}.md`, out.join("\n"));
}

