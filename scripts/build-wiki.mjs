// Fields that, when present and false, hide an entry from some surface.
const HIDE_FLAGS = [
  { test: (e) => e.publicListing === false, label: "publicListing: false" },
  { test: (e) => e.onFilmsPage === false, label: "onFilmsPage: false" },
  { test: (e) => e.repoPublic === false, label: "repoPublic: false" },
  { test: (e) => typeof e.notShownReason === "string", label: (e) => `notShownReason: ${oneLine(e.notShownReason)}` },
];

// A comment block is a guard when it says what must not happen.
const GUARD_RE =
  /\b(do not|don't|never|must not|not shown|not show|off every|off the readme|kept off|held off|no logo|not on|not be shown|on purpose|not linked|stays off|until (she|chan) clears)\b/i;

// ---------------------------------------------------------------------------------------------
// helpers
// ---------------------------------------------------------------------------------------------
function oneLine(s, max = 240) {
  const t = String(s).replace(/\s+/g, " ").trim();
  return t.length > max ? t.slice(0, max - 1).trimEnd() + "…" : t;
}

function getPath(obj, dotted) {
  // Returns the list of leaf values at a dotted path; "a[]" walks an array.
  let cur = [obj];
  for (const seg of dotted.split(".")) {
    const arr = seg.endsWith("[]");
    const key = arr ? seg.slice(0, -2) : seg;
    const next = [];
    for (const c of cur) {
      if (c == null || typeof c !== "object") continue;
      const v = c[key];
      if (v == null) continue;
      if (arr) {
        if (Array.isArray(v)) next.push(...v);
      } else next.push(v);
    }
    cur = next;
  }
  return cur.flatMap((v) => (Array.isArray(v) ? v : [v])).filter((v) => v != null && v !== "");
}

function displayName(list, e) {
  const n =
    e.name ?? e.title ?? e.label ?? e.institution ?? (list === "openSourceContributions" ? e.title : undefined);
  if (list === "work" || list === "volunteer") {
    if (e.position && e.name) return `${e.position}, ${e.name}`;
  }
  if (list === "education" && e.studyType && e.institution) return `${e.studyType}, ${e.institution}`;
  if (n) return oneLine(n, 160);
  return e.id;
}

function summaryOf(e) {
  for (const k of ["tagline", "publicSummary", "summary", "description", "blurb", "impact", "position", "role"]) {
    const v = e[k];
    if (typeof v === "string" && v.trim()) return oneLine(v);
  }
  if (typeof e.reference === "string") return oneLine(e.reference);
  return null;
}

const DATE_KEYS = ["startDate", "endDate", "date", "releaseDate", "since", "mergedAt", "closedAt"];

function wl(list, id) {
  return `[[${list}/${id}]]`;
}

function readUtf8(p) {
  return fs.readFileSync(p, "utf8");
}

