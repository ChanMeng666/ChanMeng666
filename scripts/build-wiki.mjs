const TIER_ORDER = ["flagship", "primary", "secondary", "archive"];
const GROUP_BY = {
  projects: ["tier", "status"],
  films: ["kind"],
  organizations: ["type"],
  publications: ["tier"],
  events: ["type"],
  openSourceContributions: ["type"],
  references: ["tier"],
  collaborators: ["tier"],
  showcase: ["capability"],
  work: ["tier"],
  volunteer: ["tier"],
};

function orderKeys(keys, field) {
  const rank = (k) => (field === "tier" && TIER_ORDER.includes(k) ? TIER_ORDER.indexOf(k) : 100);
  return [...keys].sort((a, b) => rank(a) - rank(b) || (a === "(none)") - (b === "(none)"));
  // insertion (file) order otherwise: Array.prototype.sort is stable
}

function hubLine(list, e) {
  const m = meta.get(`${list}/${e.id}`);
  const bits = [];
  for (const k of ["status", "tier", "recency"]) {
    if (e[k] != null && !(GROUP_BY[list] ?? []).includes(k)) bits.push(e[k]);
  }
  const d = e.startDate ?? e.date ?? e.releaseDate;
  if (d) bits.push(String(d));
  const hidden = guardRows.some((g) => g.key === `${list}/${e.id}`) ? " · guarded" : "";
  return `- [[${list}/${e.id}]] ${m.name}${bits.length ? ` (${bits.join(", ")})` : ""}${hidden}`;
}

for (const list of entityLists) {
  const items = data[list].filter((e) => e?.id);
  const out = [HEADER, "", `# ${list}`, "", `${items.length} entries. Back to [[index]].`, ""];
  const fields = GROUP_BY[list] ?? (items.some((e) => e.tier) ? ["tier"] : []);
  function emit(subset, depth) {
    if (depth >= fields.length) {
      for (const e of subset) out.push(hubLine(list, e));
      out.push("");
      return;
    }
    const f = fields[depth];
    const groups = new Map();
    for (const e of subset) {
      const g = e[f] == null || typeof e[f] === "object" ? "(none)" : String(e[f]);
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g).push(e);
    }
    for (const g of orderKeys(groups.keys(), f)) {
      out.push(`${"#".repeat(depth + 2)} ${f}: ${g} (${groups.get(g).length})`, "");
      emit(groups.get(g), depth + 1);
    }
  }
  emit(items, 0);
  pages.set(`${list}.md`, out.join("\n"));
}

// guards hub
{
  const out = [
    HEADER,
    "",
    "# Guards and hidden entries",
    "",
    "Every entry with a visibility flag that hides it (`show.*: false`, `publicListing: false`,",
    "`onFilmsPage: false`, `notShownReason`, `repoPublic: false`) or a guard comment in its shard",
    "(the comment block directly above the entry, or a comment inside it, that says what must not",
    "happen). The display rules themselves are in docs/STATE.md § Display rules. Back to [[index]].",
    "",
  ];
  const byList = new Map();
  for (const g of guardRows) {
    if (!byList.has(g.list)) byList.set(g.list, new Map());
    const m = byList.get(g.list);
    if (!m.has(g.key)) m.set(g.key, []);
    m.get(g.key).push(g);
  }
  let n = 0;
  for (const list of entityLists) {
    const m = byList.get(list);
    if (!m) continue;
    out.push(`## ${list} (${m.size})`, "");
    for (const [key, rows] of m) {
      n++;
      out.push(`- [[${key}]] ${rows[0].name}`);
      for (const r of rows) out.push(`  - ${r.kind}${r.kind === "flag" ? "" : `, \`${r.shard}:${r.line}\``}: ${oneLine(r.text, 100000)}`);
    }
    out.push("");
  }
  out.splice(9, 0, `${n} entries.`, "");
  pages.set("guards.md", out.join("\n"));
}

